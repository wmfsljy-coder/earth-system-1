/* 지구시스템과학1 Ⅰ-2 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js·worked.js 다음에 불러온다.
   02(판의 경계)는 01의 해양저 확장과 '거리 = 속도 × 나이'에, 03(화산)은 02의 판 경계·열점에 기댄다.
   04(지진파)는 사건 파일에 필요한 것이 다 있어 앞 소단원 없이 시작한다. */
(function () {
"use strict";

var D01 = [
  "<b>해령</b>에서 마그마가 올라와 새 해양 지각이 생기고 양쪽으로 밀려 난다(해양저 확장). 그래서 해령에서 멀수록 해양 지각이 오래되었고, 고지자기 줄무늬가 해령을 축으로 대칭을 이룬다.",
  "<b>해령에서의 거리 = 확장 속도 × 나이</b>. 대서양 중앙 해령은 한쪽으로 약 2.5 cm/년이므로 1억 년이면 약 2,500 km 옮겨 간다.",
  "암석에 남은 <b>복각</b>으로 그 암석이 만들어진 때의 위도를 알 수 있다. 이것이 대륙이 움직였다는 증거다."
];
var D02 = [
  "판 경계는 세 가지다. 두 판이 멀어지면 <b>발산형</b>(해령), 다가서면 <b>수렴형</b>(해구·섭입대), 스쳐 지나가면 <b>보존형</b>(변환 단층).",
  "화산은 해령과 섭입대(호상 열도) 같은 <b>판 경계</b>에서 주로 생기지만, 하와이처럼 맨틀 깊은 곳의 거의 고정된 열기둥 위, 곧 <b>열점</b>에서 판 한가운데에 생기기도 한다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「판의 경계와 이동의 원동력」에서 해령·해구를 경계의 종류로 다시 나누고, 하와이 화산섬의 <b>나이와 거리</b>로 태평양판의 속도를 구합니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], D01[1], "이 이야기에서는 열점에서 태어나 판에 실려 옮겨 간 화산섬의 나이와 거리로 <b>판의 속도</b>를 구합니다."],
  check: { q: "해령에서 1,000 km 떨어진 해양 지각의 나이가 4,000만 년이다. 확장 속도는?", options: ["0.4 cm/년", "2.5 cm/년", "4 cm/년", "25 cm/년"], a: 1, why: "1,000 km = 1억 cm, 1억 cm ÷ 4,000만 년 = 2.5 cm/년." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「화산 활동과 암석의 순환」에서는 판 안쪽의 화산인 한라산과 백두산이 왜 그렇게 다르게 생겼는지 <b>마그마</b>로 설명합니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[1], "이 이야기의 한라산과 백두산은 둘 다 <b>판 경계가 아닌 판 안쪽</b>의 화산입니다. 그래서 ‘어디에서 터졌나’가 아니라 <b>마그마의 성분</b>으로 차이를 설명합니다."],
  check: { q: "하와이처럼 판 한가운데에 화산섬이 줄지어 생기는 곳을 무엇이라 할까?", options: ["해령", "해구", "열점"], a: 2, why: "맨틀 깊은 곳의 거의 고정된 열기둥(열점) 위를 판이 지나가며 화산이 줄지어 생깁니다." }
});
})();
