/* 지구시스템과학1 Ⅰ-1 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js 다음에 불러온다.
   02(산소)·03(물과 탄소)은 둘 다 01이 만든 '네 권역'과 '원시 대기·원시 바다'에 기대고, 02와 03 사이에는 기대는 것이 없다. */
(function () {
"use strict";

var D01 = [
  "지구시스템의 네 권역은 차례로 갖춰졌다. 마그마 바다의 층상 분화로 <b>지권</b>(핵·맨틀·지각) → 화산 기체(수증기·이산화 탄소)로 <b>기권</b>(원시 대기) → 수증기가 비가 되어 <b>수권</b>(원시 바다) → 바닷속 생명체로 <b>생물권</b>.",
  "원시 바다가 생기자 대기의 <b>이산화 탄소가 바닷물에 녹아 석회암(탄산염 암석)으로 묻혔다</b>. 그래서 지구 대기는 금성처럼 두꺼운 이산화 탄소 대기가 되지 않았다.",
  "이산화 탄소·수증기 같은 <b>온실 기체가 많을수록 지표가 따뜻해진다</b>(온실 효과). 물이 끝내 응결하지 못한 금성은 폭주 온실이 되었다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「산소의 순환과 대산소화 사건」에서는 <b>네 권역</b>이 산소 때문에 차례로 바뀌는 과정을, 03 「물과 탄소의 순환」에서는 <b>이산화 탄소가 석회암으로 묻히는 길</b>과 <b>온실 효과</b>가 지구의 온도를 정하는 과정을 다시 봅니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], "이 이야기에서는 <b>생물권</b>(남세균)이 만든 산소가 <b>수권</b>(바닷속 철 이온) → <b>지권</b>(해저의 호상철광층) → <b>기권</b>(대기·오존층)을 차례로 바꿉니다. 이야기가 시작될 무렵의 원시 바다와 원시 대기에는 산소가 거의 없었습니다."],
  check: { q: "지구시스템의 네 권역 가운데 원시 바다가 속하는 것은?", options: ["기권", "수권", "지권", "생물권"], a: 1, why: "바다·빙하·지하수처럼 지구의 물은 모두 수권입니다." }
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: [D01[1], D01[2], "이 이야기에서는 화산이 내보내는 이산화 탄소와, 빗물의 풍화로 석회암에 묻히는 이산화 탄소가 <b>균형을 이루는 곳</b>에서 지구의 기온이 정해집니다."],
  check: { q: "원시 지구 대기의 이산화 탄소가 크게 줄어든 까닭으로 알맞은 것은?", options: ["우주로 빠져나가서", "원시 바다에 녹아 석회암(탄산염 암석)으로 묻혀서", "육지의 식물이 모두 흡수해서"], a: 1, why: "바다에 녹은 이산화 탄소가 탄산염 암석으로 쌓였습니다. 육상 식물은 그보다 수십억 년 뒤에 나타났습니다." }
});
})();
